#!/usr/bin/env bash
# Lists every MP3 under server/music with its bitrate, sample rate, channels,
# length and size, so low-quality rips stand out. Writes server/music/TRACKS.md
# and prints the same table.
#
#   ./scripts/music-report.sh            # all folders
#   ./scripts/music-report.sh christmas  # one folder
#
# Needs ffprobe (part of ffmpeg). Rows under LOW_KBPS are flagged; anything
# that low (or at 11.025 kHz mono) sounds like AM radio next to a 320 kbps rip
# and is the first thing to replace.

set -euo pipefail
cd "$(dirname "$0")/.."

MUSIC_ROOT="server/music"
OUT="${MUSIC_ROOT}/TRACKS.md"
LOW_KBPS="${LOW_KBPS:-96}"

if ! command -v ffprobe >/dev/null 2>&1; then
  echo "ffprobe not found; install ffmpeg first" >&2
  exit 1
fi

folders=()
if [[ $# -gt 0 ]]; then
  for f in "$@"; do folders+=("${MUSIC_ROOT}/${f}"); done
else
  while IFS= read -r d; do folders+=("$d"); done < <(find "${MUSIC_ROOT}" -mindepth 1 -maxdepth 1 -type d | sort)
fi

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

for dir in "${folders[@]}"; do
  [[ -d "$dir" ]] || { echo "no such folder: $dir" >&2; continue; }
  while IFS= read -r -d '' f; do
    ffprobe -v error -select_streams a:0 \
      -show_entries stream=sample_rate,channels,bit_rate:format=duration,bit_rate,size \
      -of json "$f" \
    | python3 -c '
import json, sys, os
d = json.load(sys.stdin)
a = d["streams"][0]
fm = d["format"]
kbps = int(a.get("bit_rate") or fm.get("bit_rate") or 0) // 1000
folder = os.path.basename(os.path.dirname(sys.argv[1]))
name = os.path.basename(sys.argv[1])
minutes = float(fm["duration"]) / 60
megabytes = int(fm["size"]) / 1e6
print("\t".join([folder, name, str(kbps), a["sample_rate"], str(a["channels"]),
                 f"{minutes:.1f}", f"{megabytes:.1f}"]))
' "$f" >> "$tmp"
  done < <(find "$dir" -type f -iname '*.mp3' -print0 | sort -z)
done

# Sort by folder, then bitrate ascending so the weak rips lead each section.
sort -t $'\t' -k1,1 -k3,3n "$tmp" -o "$tmp"

{
  echo "# Music library"
  echo
  echo "Generated by \`scripts/music-report.sh\` on $(date +%Y-%m-%d). Rows marked **LOW** are"
  echo "under ${LOW_KBPS} kbps and worth replacing with a better rip."
  echo
  echo "| Folder | Track | kbps | Hz | Ch | Min | MB | |"
  echo "|---|---|---:|---:|---:|---:|---:|---|"
  awk -F '\t' -v low="${LOW_KBPS}" '{
    flag = ($3 + 0 < low) ? "**LOW**" : ""
    printf "| %s | %s | %s | %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6, $7, flag
  }' "$tmp"
  echo
  echo "## Summary"
  echo
  awk -F '\t' -v low="${LOW_KBPS}" '
    { n[$1]++; if ($3 + 0 < low) l[$1]++; mb[$1] += $7 }
    END { for (f in n) printf "- **%s**: %d tracks, %d low bitrate, %.0f MB\n", f, n[f], l[f] + 0, mb[f] }
  ' "$tmp" | sort
} > "$OUT"

printf '%-10s %-52s %5s %6s %3s %5s %5s  %s\n' folder track kbps Hz ch min MB ''
awk -F '\t' -v low="${LOW_KBPS}" '{
  flag = ($3 + 0 < low) ? "LOW" : ""
  printf "%-10s %-52s %5s %6s %3s %5s %5s  %s\n", $1, substr($2, 1, 52), $3, $4, $5, $6, $7, flag
}' "$tmp"
echo
echo "written: $OUT"
